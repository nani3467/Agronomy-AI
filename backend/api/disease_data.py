def get_disease_details(disease_name: str) -> dict:
    """Lookup rich disease intelligence details with fuzzy matching."""
    if not disease_name:
        return DEFAULT_DISEASE_INFO.copy()

    # Direct match
    if disease_name in DISEASE_DATABASE:
        data = DISEASE_DATABASE[disease_name].copy()
        data['disease_name'] = disease_name
        return data

    # Case-insensitive match
    lower_name = disease_name.strip().lower()
    for name, data in DISEASE_DATABASE.items():
        if name.lower() == lower_name:
            res = data.copy()
            res['disease_name'] = name
            return res

    # Substring match
    for name, data in DISEASE_DATABASE.items():
        if lower_name in name.lower() or name.lower() in lower_name:
            res = data.copy()
            res['disease_name'] = name
            return res

    # Healthy match fallback
