def get_crop_details(crop_name: str) -> dict:
    """Retrieve structured agronomic intelligence for any crop name."""
    if not crop_name:
        return DEFAULT_CROP_INFO.copy()

    norm = crop_name.strip().lower().replace(' ', '').replace('-', '').replace('(', '').replace(')', '')

    # Try direct key or matching normalized key
    for k, data in CROPS_DATABASE.items():
        k_norm = k.lower().replace(' ', '').replace('-', '')
        name_norm = data['name'].lower().replace(' ', '').replace('-', '').replace('(', '').replace(')', '')
        if k_norm == norm or name_norm == norm or norm in k_norm or k_norm in norm or norm in name_norm or name_norm in norm:
            res = data.copy()
            return res

    fallback = DEFAULT_CROP_INFO.copy()
    fallback['name'] = crop_name.title()
    return fallback
